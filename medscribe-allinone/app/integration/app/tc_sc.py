TRAD_TO_SIMP: dict[str, str] = {}
for _t, _s in _PAIRS:
    TRAD_TO_SIMP.setdefault(_t, _s)


def to_simplified(text: str) -> str:
    """逐字折叠为简体，长度与原串一致（可安全用于下标回填）。"""
    if not text:
        return text
    if not any(ch in TRAD_TO_SIMP for ch in text):
        return text
    return "".join(TRAD_TO_SIMP.get(ch, ch) for ch in text)


def has_traditional(text: str) -> bool:
    return any(ch in TRAD_TO_SIMP for ch in text)
